using J = nlohmann::ordered_json;

std::string num(double v) {
    char buf[40];
    std::snprintf(buf, sizeof buf, "%.10g", v);
    return buf;
}

std::string rangeText(const ParamDef& p) {
    if (p.type == ParamType::Bool)
        return "off, on";
    if (p.type == ParamType::Choice) {
        std::string out;
        for (std::size_t i = 0; i < p.choices.size(); ++i)
            out += (i ? ", " : "") + p.choices[i];
        return out;
    }
    return num(p.min) + " .. " + num(p.max);
}

std::string defaultText(const ParamDef& p) {
    if (p.type == ParamType::Bool)
        return p.def >= 0.5 ? "on" : "off";
    if (p.type == ParamType::Choice)
        return p.choices[static_cast<std::size_t>(p.def)];
    return num(p.def);
}

std::string skewText(const ParamDef& p) {
    if (p.stepped())
        return "-";
    if (p.skew == Skew::Power)
        return "power " + num(p.skewExp);
    return std::string(skewLabel(p.skew));
}

std::string code(const std::string& s) { return s.empty() ? "-" : "`" + s + "`"; }

const char* kHeader = "| Id | Name | Type | Range | Default | Unit | Skew | Smoothing | Host | Mod | Scope | Patch field | Description |\n"
                      "|---|---|---|---|---|---|---|---|---|---|---|---|---|\n";

void row(std::string& out, const ParamDef& p, const std::string& id, const std::string& pointer) {
    const std::string unit(unitLabel(p.unit));
    out += "| `" + id + "` | " + p.name + " | " + std::string(typeLabel(p.type)) + " | " + rangeText(p) + " | " +
           defaultText(p) + " | " + (unit.empty() ? "-" : unit) + " | " + skewText(p) + " | " +
           std::string(smoothingLabel(p.smoothing)) + " | " + (p.automatable ? "yes" : "no") + " | " +
           (p.modulatable ? "yes" : "no") + " | " + std::string(scopeLabel(p.scope)) + " | " + code(pointer) + " | " +
           p.description + " |\n";
}

J defaultJson(const ParamDef& p) {
    if (p.type == ParamType::Bool)
        return p.def >= 0.5;
    if (p.type == ParamType::Choice)
        return p.choices[static_cast<std::size_t>(p.def)];
    return p.def;
}

J paramJson(const ParamDef& p, bool registryParam) {
    J o = J::object();
    o["id"] = p.id;
    o["name"] = p.name;
    if (registryParam)
        o["module"] = p.module;
    o["type"] = typeLabel(p.type);
    if (p.type == ParamType::Choice) {
        o["choices"] = p.choices;
    } else if (p.type != ParamType::Bool) {
        o["min"] = p.min;
        o["max"] = p.max;
    }
    o["default"] = defaultJson(p);
    o["unit"] = unitLabel(p.unit);
    if (!p.stepped()) {
        o["skew"] = skewLabel(p.skew);
        if (p.skew == Skew::Power)
            o["skew_exponent"] = p.skewExp;
    }
    o["smoothing"] = smoothingLabel(p.smoothing);
    o["scope"] = scopeLabel(p.scope);
    o["automatable"] = p.automatable;
    o["modulatable"] = p.modulatable;
    if (registryParam) {
        o["host_id"] = p.hostId;
        o["patch_pointer"] = p.pointer;
    } else {
        o["patch_key"] = p.pointer;
        o["slot_param"] = p.index + 1;
    }
    o["description"] = p.description;
    return o;
}

