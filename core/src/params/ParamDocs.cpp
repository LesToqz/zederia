std::string registryMarkdown() {
    const auto& reg = Registry::get();
    int automatable = 0;
    for (const auto& p : reg.params())
        automatable += p.automatable ? 1 : 0;

    std::string out = "# Parameters\n\n";
    out += "Generated by `zederia-cli params --format md` from the parameter registry "
           "(`core/src/params/Registry.cpp`). Do not edit by hand; a test fails when this file is out of date.\n\n";
    out += std::to_string(reg.size()) + " parameters in " + std::to_string(reg.modules().size()) + " modules; " +
           std::to_string(automatable) + " are exposed to the host.\n\n";
    out += "## How to read the tables\n\n"
           "- **Id** is permanent. The host's 32-bit parameter id is a hash of it, so adding parameters never renumbers existing ones.\n"
           "- **Range** and **Default** are in the unit shown. `%` values are stored as fractions: 0.25 means 25 %. "
           "Levels at or below -72 dB are silence.\n"
           "- **Skew** is how the host's 0..1 value maps onto the range: `linear`, `log` (equal steps are equal ratios) "
           "or `power n` (range x position^n, fine resolution near the minimum).\n"
           "- **Smoothing**: `none` is taken as is at the next control tick, `control` is smoothed at the control rate "
           "(every 16 samples), `sample` is also interpolated per sample.\n"
           "- **Host**: exposed to the host for automation. **Mod**: can be the destination of a modulation route.\n"
           "- **Scope**: `voice` values exist once per voice, `global` values once per instrument. "
           "A route is polyphonic when both its source and destination are per-voice.\n"
           "- **Patch field** is the JSON pointer of the value inside a patch document. Choices are written as their "
           "names, switches as `true`/`false`.\n\n";

    bool macrosDone = false, routesDone = false, slotsDone = false;
    for (const auto& m : reg.modules()) {
        const auto rows = [&](std::string& text) {
            for (int i = m.firstParam; i < m.firstParam + m.numParams; ++i)
                row(text, reg.at(i), reg.at(i).id, reg.at(i).pointer);
        };
        switch (m.kind) {
        case ModuleKind::Plain:
        case ModuleKind::FxRack:
            out += "## " + m.name + " (`" + m.id + "`)\n\n" + m.description + "\n\n" + kHeader;
            rows(out);
            out += "\n";
            break;
        case ModuleKind::Macro:
            if (!macrosDone) {
                out += "## Macros (`macro1` .. `macro" + std::to_string(kNumMacros) + "`)\n\n" + m.description +
                       " In a patch, `macros` is a list; entry N also holds the macro's `name`.\n\n" + kHeader;
                macrosDone = true;
            }
            rows(out);
            if (m.id == "macro" + std::to_string(kNumMacros))
                out += "\n";
            break;
        case ModuleKind::ModRoute:
            if (!routesDone) {
                routesDone = true;
                out += "## Modulation routes (`mod.1` .. `mod." + std::to_string(kNumModRoutes) + "`)\n\n"
                       "Each of the " + std::to_string(kNumModRoutes) +
                       " routes has one parameter, shown here for route N. In a patch, `mod` is a list and entry N-1 "
                       "holds route N with these fields: `source`, `via` (optional), `via_invert`, `dest` (a parameter id "
                       "marked Mod), `amount`, `polarity` (`bi`, `uni`), `curve` (`linear`, `exp`, `log`, `s`, `drawn`), "
                       "`enabled`, `mute`, `solo`.\n\n" + kHeader;
                row(out, reg.at(m.firstParam), "mod.N.amount", "/mod/N-1/amount");
                out += "\n";
            }
            break;
        case ModuleKind::FxSlot:
            if (!slotsDone) {
                slotsDone = true;
                out += "## Effect slots (`fx.a1` .. `fx.a8`, `fx.b1` .. `fx.b8`, `fx.m1` .. `fx.m8`)\n\n"
                       "Every slot of lanes A, B and Master has the same " + std::to_string(m.numParams) +
                       " parameters, shown here for slot `fx.<slot>`. `p1` .. `p" + std::to_string(kNumFxSlotParams) +
                       "` are generic: they take the name, range and unit of the loaded effect's parameters (see "
                       "Effects below) and hold values in that parameter's own unit. In a patch, `fx.a`, `fx.b` and "
                       "`fx.master` are lists of slots; each slot has `type`, `on`, `mix` and the effect's parameters "
                       "under their own names.\n\n" + kHeader;
                for (int i = m.firstParam; i < m.firstParam + m.numParams; ++i) {
                    const ParamDef& p = reg.at(i);
                    const std::string key = p.id.substr(p.id.rfind('.') + 1);
                    row(out, p, "fx.<slot>." + key, p.pointer.empty() ? "" : "/fx/<lane>/<n>/" + key);
                }
                out += "\n";
            }
            break;
        }
    }

    out += "## Effects\n\nThe effect types a slot can hold. **Slot** is the generic slot parameter each one maps to.\n\n";
    for (const auto& e : reg.effectTypes()) {
        out += "### " + e.name + " (`" + e.id + "`)\n\n" + e.description + "\n\n";
        out += "| Slot | Patch field | Name | Type | Range | Default | Unit | Skew | Description |\n|---|---|---|---|---|---|---|---|---|\n";
        for (const auto& p : e.params) {
            const std::string unit(unitLabel(p.unit));
            out += "| p" + std::to_string(p.index + 1) + " | `" + p.pointer + "` | " + p.name + " | " +
                   std::string(typeLabel(p.type)) + " | " + rangeText(p) + " | " + defaultText(p) + " | " +
                   (unit.empty() ? "-" : unit) + " | " + skewText(p) + " | " + p.description + " |\n";
        }
        out += "\n";
    }

    out += "## Modulation sources\n\nValues for a route's `source` and `via`. MIDI controllers are written `cc0` .. `cc127`.\n\n"
           "| Id | Name | Scope | Description |\n|---|---|---|---|\n";
    for (const auto& s : reg.modSources())
        out += "| `" + s.id + "` | " + s.name + " | " + std::string(scopeLabel(s.scope)) + " | " + s.description + " |\n";

    out += "\n## Tempo divisions\n\nUsed by every synced rate. `D` is dotted, `T` is triplet.\n\n";
    for (std::size_t i = 0; i < tempoDivisions().size(); ++i)
        out += (i ? ", `" : "`") + tempoDivisions()[i] + "`";
    out += "\n";
    return out;
}

std::string registryJson() {
    const auto& reg = Registry::get();
    J doc = J::object();
    doc["format"] = "zederia.params";
    doc["zederia_version"] = kVersion;
    doc["count"] = reg.size();
    J modules = J::array();
    for (const auto& m : reg.modules())
        modules.push_back({{"id", m.id}, {"name", m.name}, {"description", m.description}});
    doc["modules"] = std::move(modules);
    J params = J::array();
    for (const auto& p : reg.params())
        params.push_back(paramJson(p, true));
    doc["params"] = std::move(params);
    J effects = J::array();
    for (const auto& e : reg.effectTypes()) {
        J list = J::array();
        for (const auto& p : e.params)
            list.push_back(paramJson(p, false));
        effects.push_back({{"id", e.id}, {"name", e.name}, {"description", e.description}, {"params", std::move(list)}});
    }
    doc["effects"] = std::move(effects);
    J sources = J::array();
    for (const auto& s : reg.modSources())
        sources.push_back({{"id", s.id}, {"name", s.name}, {"scope", scopeLabel(s.scope)}, {"description", s.description}});
    doc["mod_sources"] = std::move(sources);
    doc["tempo_divisions"] = tempoDivisions();
    return doc.dump(2) + "\n";
}

